// YDS 換算照 Mountain Project 對照表，邏輯與 scripts/climbing-grade-convert.mjs 的 toYds() 完全一致
// （同一張 FR 表、同一個複合級數取法、近似級加「約」），避免兩邊算出不同值。
const FR = {
  '3a': '5.2', '3b': '5.3', '3c': '5.3', '4a': '5.4', '4b': '5.5', '4c': '5.6', '5a': '5.7', '5b': '5.8', '5c': '5.9',
  '6a': '5.10a', '6a+': '5.10b', '6b': '5.10c', '6b+': '5.10d', '6c': '5.11a/b', '6c+': '5.11c', '7a': '5.11d',
  '7a+': '5.12a', '7b': '5.12b', '7b+': '5.12c', '7c': '5.12d', '7c+': '5.13a', '8a': '5.13b', '8a+': '5.13c',
  '8b': '5.13d', '8b+': '5.14a', '8c': '5.14b', '8c+': '5.14c', '9a': '5.14d', '9a+': '5.15a', '9b': '5.15b',
  '9b+': '5.15c', '9c': '5.15d',
};
const FR_APPROX = { '3': '5.2', '3+': '5.3', '4': '5.4–5.5', '4+': '5.6', '5': '5.7–5.8', '5+': '5.9', '5c+': '5.9+' };
const FR_RE = /(?<![\w.])([3-9][abc]\+?|[3-5]\+?)(?![\w.])/g;

function yds(cell) {
  const raw = (cell ?? '').trim();
  if (!raw || raw === '—' || raw === '-') return '—';
  if (/^5\.\d/.test(raw)) return null;
  const grades = [...raw.matchAll(FR_RE)].map((m) => m[1]).filter((g) => FR[g] || FR_APPROX[g]);
  if (!grades.length) return '—';
  if (FR[grades[0]]) return FR[grades[0]];
  return `約 ${FR_APPROX[grades[0]]}`;
}

function band(g) {
  if (!g) return 3;
  const m = g.match(/^(\d)/);
  if (!m) return 3;
  const n = Number(m[1]);
  if (n <= 5) return 0;
  if (n === 6) return g.slice(1) === 'a' ? 0 : 1;
  if (n === 7) return 2;
  return 3;
}

const notes = NOTE[lang];
const buckets = [[], [], [], []];
for (const r of routes) {
  const b = band(r.grade);
  const stars = r.stars ? '★'.repeat(r.stars) : '';
  buckets[b].push({ r, stars });
}
for (const b of buckets) b.sort((x, y) => (x.r.name > y.r.name ? 1 : -1));

const HEADINGS = lang === 'en'
  ? ['### Beginner: up to 6a (YDS 5.10a and below)',
     '### Intermediate: 6a+ to 6c+ (YDS 5.10b–5.11c)',
     '### Advanced: 7a to 7c+ (YDS 5.11d–5.13a)',
     '### Expert: 8a and up (YDS 5.13b and up)']
  : ['### 入門：6a 以下（YDS 5.10a 以下）',
     '### 中級：6a+ 到 6c+（YDS 5.10b–5.11c）',
     '### 進階：7a 到 7c+（YDS 5.11d–5.13a）',
     '### 高手：8a 以上（YDS 5.13b 以上）'];

