export type ChatKey = keyof (typeof chatStrings)['zh-TW']

/** 取字；`{name}` 佔位符用 vars 代入。 */
export function chatT(lang: Lang) {
  return (key: ChatKey, vars?: Record<string, string | number>): string => {
    const table = (chatStrings as Record<string, Record<ChatKey, string>>)[lang] ?? chatStrings[defaultLang]
    let text: string = table[key] ?? chatStrings[defaultLang][key]
    if (vars) for (const [k, v] of Object.entries(vars)) text = text.replace(`{${k}}`, String(v))
    return text
  }
}

